/**
 * 自官網 lv-24 同步講座場次 → src/data/sessions/synced.js
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { LECTURE } from '../src/data/company.js'
import { CANCELLED_LECTURE_FLOW_IDS } from '../src/data/sessions/overrides.js'
import { classifyThemes, inferRegion, normalizeStatus } from '../src/lib/sessionUtils.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outPath = join(root, 'src/data/sessions/synced.js')
const reportPath = join(root, '.sync-report.json')

function stripTags(html) {
  return html.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim()
}

function parseSessions(html) {
  const items = html.match(/<div class="item">[\s\S]*?(?=<div class="item">|$)/g) ?? []
  const sessions = []

  for (const item of items) {
    const flowMatch = item.match(/lecture-flow\.html\?id=(\d+)/)
    if (!flowMatch) continue

    const dateMatch = item.match(/class="date"[\s\S]*?<div>([\s\S]*?)<\/div>/)
    const timeMatch = item.match(/class="time"[\s\S]*?<div>([\s\S]*?)<\/div>/)
    const titleMatch = item.match(/class="locate-ti">([\s\S]*?)<\/div>/)
    const locMatch = item.match(/class="locate-loc">([\s\S]*?)<\/div>/)
    const qtyMatch = item.match(/class="qty"[\s\S]*?<div>([\s\S]*?)<\/div>/)
    const endMatch = item.match(/class="end"[\s\S]*?<div>([\s\S]*?)<\/div>/)
    const statusMatch = item.match(/class="status"[\s\S]*?<div>([\s\S]*?)<\/div>/)

    const dateRaw = stripTags(dateMatch?.[1] ?? '').split('【')[0].trim()
    const title = stripTags(titleMatch?.[1] ?? '')
    const location = stripTags(locMatch?.[1] ?? '')
    const lectureFlowId = Number(flowMatch[1])

    if (!dateRaw || !title) continue

    const date = dateRaw.replace(/-/g, '/')
    const id = `${date.replace(/\//g, '-')}-flow-${lectureFlowId}`

    sessions.push({
      id,
      title,
      date,
      time: stripTags(timeMatch?.[1] ?? ''),
      location,
      region: inferRegion(location),
      capacity: Number(stripTags(qtyMatch?.[1] ?? '0')) || 0,
      deadline: stripTags(endMatch?.[1] ?? date).replace(/-/g, '/'),
      statusRaw: stripTags(statusMatch?.[1] ?? ''),
      lectureFlowId,
      themes: classifyThemes(title),
      status: normalizeStatus(stripTags(statusMatch?.[1] ?? '')),
    })
  }

  return sessions
}

function loadPrevious() {
  if (!existsSync(outPath)) return []
  try {
    const mod = readFileSync(outPath, 'utf8')
    const match = mod.match(/export const SESSIONS = (\[[\s\S]*?\])\n/s)
    if (!match) return []
    return JSON.parse(match[1])
  } catch {
    return []
  }
}

function diffSessions(prev, next) {
  const prevMap = new Map(prev.map((s) => [s.lectureFlowId, s]))
  const nextMap = new Map(next.map((s) => [s.lectureFlowId, s]))
  const added = next.filter((s) => !prevMap.has(s.lectureFlowId))
  const removed = prev.filter((s) => !nextMap.has(s.lectureFlowId))
  const changed = next.filter((s) => {
    const old = prevMap.get(s.lectureFlowId)
    if (!old) return false
    return JSON.stringify(old) !== JSON.stringify(s)
  })
  return { added, removed, changed, hasChanges: added.length + removed.length + changed.length > 0 }
}

async function main() {
  const res = await fetch(LECTURE.listUrl)
  if (!res.ok) throw new Error(`同步失敗 HTTP ${res.status}`)
  const html = await res.text()
  const sessions = parseSessions(html).filter(
    (s) => !CANCELLED_LECTURE_FLOW_IDS.includes(s.lectureFlowId),
  )

  if (sessions.length === 0) {
    throw new Error('解析不到任何場次，可能官網 HTML 結構已變更')
  }

  const previous = loadPrevious()
  const report = diffSessions(previous, sessions)
  const syncedAt = new Date().toLocaleString('sv-SE', { timeZone: 'Asia/Taipei' }).replace(' ', 'T') + '+08:00'

  const file = `// AUTO-GENERATED by scripts/sync-sessions.mjs — do not edit manually
export const SYNC_META = ${JSON.stringify(
    {
      lastSyncedAt: syncedAt,
      sourceUrl: LECTURE.listUrl,
      sessionCount: sessions.length,
    },
    null,
    2,
  )}

export const SESSIONS = ${JSON.stringify(sessions, null, 2)}
`

  mkdirSync(dirname(outPath), { recursive: true })
  writeFileSync(outPath, file, 'utf8')
  writeFileSync(
    reportPath,
    JSON.stringify({ syncedAt, ...report, sessionCount: sessions.length }, null, 2),
    'utf8',
  )

  console.log(`已同步 ${sessions.length} 場講座 → src/data/sessions/synced.js`)
  if (report.hasChanges) {
    console.log(`變更：新增 ${report.added.length}、移除 ${report.removed.length}、更新 ${report.changed.length}`)
    console.log('請重新執行 npm run build:all 並貼回 CMS')
  }
}

main().catch((err) => {
  console.error(err.message)
  process.exit(1)
})
